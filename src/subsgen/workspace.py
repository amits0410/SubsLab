"""Workspace composition independent of subtitle editing and inference logic."""
from PySide6.QtCore import Qt
from PySide6.QtMultimedia import QAudioOutput, QMediaPlayer
from PySide6.QtWidgets import (
    QCheckBox, QComboBox, QFormLayout, QFrame, QGridLayout, QHBoxLayout,
    QLabel, QLineEdit, QProgressBar, QPushButton, QScrollArea, QSlider,
    QSplitter, QStackedWidget, QStatusBar, QVBoxLayout, QWidget,
)

from .domain import TranscriptionMode
from .ui_widgets import SubtitleVideoWidget
from .waveform import WaveformWidget


def section_label(text):
    label = QLabel(text)
    label.setObjectName("sectionTitle")
    return label


def build_workspace(self):
    central = QWidget()
    root = QVBoxLayout(central)
    root.setContentsMargins(14, 12, 14, 8)
    root.setSpacing(10)
    self.splitter = QSplitter(Qt.Orientation.Horizontal)
    self.splitter.setChildrenCollapsible(False)
    left = QWidget()
    left.setMinimumWidth(360)
    left_layout = QVBoxLayout(left)
    left_layout.setContentsMargins(0, 0, 8, 0)
    left_layout.setSpacing(10)
    media_row = QHBoxLayout()
    media_row.addWidget(section_label("Preview"))
    self.media_label = QLabel("No media selected")
    self.media_label.setObjectName("muted")
    self.media_label.setMinimumWidth(0)
    self.media_label.setWordWrap(True)
    media_row.addWidget(self.media_label, 1)
    self.setup_toggle = QPushButton("Generate subtitles ▾")
    self.setup_toggle.setCheckable(True)
    self.setup_toggle.setChecked(True)
    media_row.addWidget(self.setup_toggle)
    left_layout.addLayout(media_row)

    self.setup_panel = QFrame()
    self.setup_panel.setObjectName("panel")
    setup_layout = QVBoxLayout(self.setup_panel)
    setup_layout.setContentsMargins(12, 10, 12, 10)
    setup = QFormLayout()
    self.mode_combo = QComboBox()
    self.mode_combo.addItem("Transcribe · original language", TranscriptionMode.TRANSCRIBE)
    self.mode_combo.addItem("Translate · English subtitles", TranscriptionMode.TRANSLATE)
    self.language_combo = QComboBox()
    for label, code in (("Auto detect", None), ("Hebrew", "he"), ("English", "en"), ("Arabic", "ar"),
                        ("Spanish", "es"), ("French", "fr"), ("German", "de")):
        self.language_combo.addItem(label, code)
    setup.addRow("Task", self.mode_combo)
    setup.addRow("Language", self.language_combo)
    setup_layout.addLayout(setup)
    self.advanced_toggle = QPushButton("Advanced options ▸")
    self.advanced_toggle.setCheckable(True)
    setup_layout.addWidget(self.advanced_toggle)
    self.advanced_panel = QWidget()
    advanced = QFormLayout(self.advanced_panel)
    advanced.setContentsMargins(0, 0, 0, 0)
    self.glossary_edit = QLineEdit()
    self.glossary_edit.setPlaceholderText("Names and terms, separated by commas")
    self.glossary_edit.setToolTip("Spelling guidance for the local transcription model")
    self.denoise_check = QCheckBox("Reduce steady background noise")
    advanced.addRow("Glossary", self.glossary_edit)
    advanced.addRow(self.denoise_check)
    self.advanced_panel.hide()
    setup_layout.addWidget(self.advanced_panel)
    self.advanced_toggle.toggled.connect(self.advanced_panel.setVisible)
    buttons = QHBoxLayout()
    self.transcribe_button = QPushButton("Generate subtitles")
    self.transcribe_button.setObjectName("primary")
    self.cancel_button = QPushButton("Cancel")
    self.cancel_button.setEnabled(False)
    self.transcribe_button.clicked.connect(self.start_transcription)
    self.cancel_button.clicked.connect(self.cancel_transcription)
    buttons.addWidget(self.transcribe_button, 1)
    setup_layout.addLayout(buttons)
    left_layout.addWidget(self.setup_panel)
    self.setup_toggle.toggled.connect(self.setup_panel.setVisible)

    self.player_surface = QStackedWidget()
    self.player_surface.setMinimumHeight(180)
    self.preview_empty = QFrame()
    self.preview_empty.setObjectName("panel")
    empty_layout = QVBoxLayout(self.preview_empty)
    empty_layout.addStretch()
    title = QLabel("Your next story starts here")
    title.setObjectName("emptyTitle")
    title.setAlignment(Qt.AlignmentFlag.AlignCenter)
    title.setWordWrap(True)
    empty_layout.addWidget(title)
    detail = QLabel("Open audio or video to preview and create subtitles.\nYour media stays on this computer.")
    detail.setObjectName("muted")
    detail.setWordWrap(True)
    detail.setAlignment(Qt.AlignmentFlag.AlignCenter)
    empty_layout.addWidget(detail)
    open_media = QPushButton("Open media…")
    open_media.setObjectName("primary")
    open_media.clicked.connect(self.open_media)
    empty_layout.addWidget(open_media, 0, Qt.AlignmentFlag.AlignHCenter)
    empty_layout.addStretch()
    self.video = SubtitleVideoWidget()
    self.subtitle_overlay = self.video.overlay
    self.audio_subtitle_panel = QLabel()
    self.audio_subtitle_panel.setTextFormat(Qt.TextFormat.PlainText)
    self.audio_subtitle_panel.setAlignment(Qt.AlignmentFlag.AlignCenter)
    self.audio_subtitle_panel.setWordWrap(True)
    self.audio_subtitle_panel.setStyleSheet("QLabel { color: #e8eef4; font-size: 26px; background: #101a24; border-radius: 10px; padding: 20px; }")
    for widget in (self.preview_empty, self.video, self.audio_subtitle_panel):
        self.player_surface.addWidget(widget)
    self.player_surface.setCurrentWidget(self.preview_empty)
    left_layout.addWidget(self.player_surface, 1)

    right = QWidget()
    right.setMinimumWidth(510)
    right_layout = QVBoxLayout(right)
    right_layout.setContentsMargins(8, 0, 0, 0)
    right_layout.setSpacing(8)
    editor_heading = QHBoxLayout()
    editor_heading.addWidget(section_label("Subtitles"))
    self.cue_count_label = QLabel("0 cues")
    self.cue_count_label.setObjectName("muted")
    editor_heading.addWidget(self.cue_count_label)
    editor_heading.addStretch()
    self.warning_summary = QLabel("No readability warnings")
    self.warning_summary.setObjectName("muted")
    editor_heading.addWidget(self.warning_summary)
    right_layout.addLayout(editor_heading)
    warning_row = QHBoxLayout()
    self.fix_segment_button = QPushButton("Fix timing / speed")
    self.fix_all_button = QPushButton("Fix all timing")
    self.fix_segment_button.setToolTip("Extend or shorten the selected cue using available silence; preserve all text")
    self.fix_all_button.setToolTip("Fix timing and reading speed where space permits; preserve all text")
    self.fix_segment_button.clicked.connect(self.fix_selected_segment)
    self.fix_all_button.clicked.connect(self.fix_all_warnings)
    warning_row.addWidget(self.fix_segment_button)
    warning_row.addWidget(self.fix_all_button)
    warning_row.addStretch()
    for label, direction in (("‹", -1), ("›", 1)):
        button = QPushButton(label)
        button.setFixedWidth(32)
        button.setToolTip("Previous warning · F7" if direction < 0 else "Next warning · F8")
        button.clicked.connect(lambda _checked=False, d=direction: self._navigate_warning(d))
        warning_row.addWidget(button)
    right_layout.addLayout(warning_row)
    self.issue_feedback = QLabel()
    self.issue_feedback.setWordWrap(True)
    self.issue_feedback.setStyleSheet("color: #e7bc54;")
    self.issue_feedback.hide()
    right_layout.addWidget(self.issue_feedback)
    cards_host = QWidget()
    self.cards_layout = QVBoxLayout(cards_host)
    self.cards_layout.setContentsMargins(0, 0, 5, 0)
    self.cards_layout.setSpacing(10)
    self.cards_layout.setAlignment(Qt.AlignmentFlag.AlignTop)
    self.cards_scroll = QScrollArea()
    self.cards_scroll.setWidgetResizable(True)
    self.cards_scroll.setWidget(cards_host)
    self.cards_scroll.viewport().installEventFilter(self)
    self.cards_scroll.verticalScrollBar().installEventFilter(self)
    right_layout.addWidget(self.cards_scroll)
    self.splitter.addWidget(left)
    self.splitter.addWidget(right)
    self.splitter.setSizes([520, 730])
    root.addWidget(self.splitter, 1)

    self.job_panel = QFrame()
    self.job_panel.setObjectName("panel")
    job_layout = QHBoxLayout(self.job_panel)
    self.progress = QProgressBar()
    self.progress.setRange(0, 100)
    self.progress.setValue(0)
    self.progress.setFormat("Ready")
    self.progress.setMaximumWidth(280)
    self.progress_details = QLabel("Local processing · no transcription job running")
    self.progress_details.setObjectName("jobDetails")
    self.progress_details.setWordWrap(True)
    job_layout.addWidget(self.progress, 1)
    job_layout.addWidget(self.progress_details, 3)
    job_layout.addWidget(self.cancel_button)
    self.cancel_button.hide()
    root.addWidget(self.job_panel)
    self.waveform = WaveformWidget()
    self.waveform.seekRequested.connect(self._seek)
    self.waveform.boundaryMoved.connect(self._waveform_boundary_moved)
    root.addWidget(self.waveform)
    transport = QHBoxLayout()
    self.play_button = QPushButton("Play")
    self.play_button.setObjectName("primary")
    self.play_button.setToolTip("Play / pause · Space or K")
    self.play_button.clicked.connect(self.toggle_playback)
    self.cc_button = QPushButton("CC Subtitles")
    self.cc_button.setCheckable(True)
    self.cc_button.setChecked(True)
    self.cc_button.setToolTip("Preview subtitles over the video")
    self.cc_button.toggled.connect(lambda _checked: self._update_subtitle_preview())
    self.loop_button = QPushButton("Loop cue")
    self.loop_button.setCheckable(True)
    self.loop_button.setToolTip("Repeat the selected cue; selecting another cue updates the loop")
    self.loop_button.toggled.connect(self._loop_cue_toggled)
    self.speed_combo = QComboBox()
    self.speed_combo.setAccessibleName("Playback speed")
    for label, rate in (("0.5×", .5), ("0.75×", .75), ("1×", 1.), ("1.25×", 1.25), ("1.5×", 1.5), ("2×", 2.)):
        self.speed_combo.addItem(label, rate)
    self.speed_combo.setCurrentIndex(2)
    self.position_slider = QSlider(Qt.Orientation.Horizontal)
    self.position_slider.setAccessibleName("Playback position")
    self.position_slider.setRange(0, 0)
    self.position_slider.sliderMoved.connect(self._seek)
    self.time_label = QLabel("00:00:00.000 / 00:00:00.000")
    self.time_label.setLayoutDirection(Qt.LayoutDirection.LeftToRight)
    for widget in (self.play_button, self.cc_button, self.loop_button, self.speed_combo):
        transport.addWidget(widget)
    transport.addWidget(self.position_slider, 1)
    transport.addWidget(self.time_label)
    root.addLayout(transport)
    self.audio_output = QAudioOutput(self)
    self.player = QMediaPlayer(self)
    self.player.setAudioOutput(self.audio_output)
    self.player.setVideoOutput(self.video.video_item)
    self.player.durationChanged.connect(self._duration_changed)
    self.player.positionChanged.connect(self._position_changed)
    self.player.hasVideoChanged.connect(self._has_video_changed)
    self.player.playbackStateChanged.connect(self._playback_state_changed)
    self.player.errorOccurred.connect(lambda _error, text: self.statusBar().showMessage(f"Playback: {text}", 10000))
    self.speed_combo.currentIndexChanged.connect(lambda _index: self.player.setPlaybackRate(float(self.speed_combo.currentData())))
    self.setCentralWidget(central)
    self.setStatusBar(QStatusBar())
